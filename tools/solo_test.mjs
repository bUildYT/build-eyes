// PC-as-host (no headset) + a phone EYE in the emulator: the creatures run on the PC, the phone sees them after 2 corner taps.
import { chromium } from 'playwright';
import path from 'node:path';
const CH = path.join(process.env.LOCALAPPDATA, 'Google/Chrome/Application/chrome.exe');
const sleep = ms => new Promise(r => setTimeout(r, ms));
const ok = (c, msg) => { console.log((c ? '  ✓ ' : '  ✗ ') + msg); if (!c) process.exitCode = 1; };
const browser = await chromium.launch({ executablePath: CH, headless: true, args: ['--ignore-certificate-errors', '--use-angle=d3d11', '--use-fake-ui-for-media-stream', '--use-fake-device-for-media-stream'] });
const errs = [];
const mk = async n => { const ctx = await browser.newContext({ ignoreHTTPSErrors: true, viewport: { width: 1280, height: 800 } }); const p = await ctx.newPage(); p.on('pageerror', e => errs.push(n + ' ' + e.message)); return p; };
const S = await mk('pc');
await S.goto('https://localhost:8897/?role=pc&solo');
await S.waitForFunction(() => BE.solo && BE.W && BE.W.monsters.length >= 3, null, { timeout: 40000 });
const code = await S.evaluate(() => localStorage.getItem('be:solo'));
ok(true, `PC hosts the world alone (code ${code}), ${await S.evaluate(() => BE.W.monsters.map(m => m.mem.kind || 'beetle').join(', '))}`);
const P = await mk('phone');
await P.goto(`https://localhost:8897/?role=eye&ref=local-floor&eye=${code}`);
await P.waitForFunction(() => window.IWER_DEVICE, null, { timeout: 60000 });
await P.evaluate(() => { IWER_DEVICE.primaryInputMode = 'controller'; });
await P.click('#goEye');
await P.waitForFunction(() => BE.W && document.getElementById('start').hidden, null, { timeout: 30000 });
const T = { x: 1.42, y: .505, z: 1.28 };
const aim = async (x, y, z) => { await P.evaluate(async ([x, y, z]) => { await IWER_DEVICE.remote.dispatch('set_transform', { device: 'headset', position: { x: x + .03, y: y + .4, z: z - .12 } }); await IWER_DEVICE.remote.dispatch('look_at', { device: 'headset', target: { x, y, z } }); }, [x, y, z]); await sleep(400); };
const tap = async () => { await P.evaluate(() => IWER_DEVICE.remote.dispatch('set_select_value', { device: 'controller-right', value: 1 })); await sleep(150); await P.evaluate(() => IWER_DEVICE.remote.dispatch('set_select_value', { device: 'controller-right', value: 0 })); await sleep(300); };
await aim(T.x - .1485, T.y, T.z + .05); await tap(); await aim(T.x + .1485, T.y, T.z + .05); await tap();
await sleep(2500);
const n = await P.evaluate(() => BE.W.monsters.length);
ok(n >= 3, `phone shows the PC's creatures (${n})`);
ok(await P.evaluate(() => BE.W.monsters.some(m => m.mem.kind === 'dragon')), 'the dragon is among them on the phone');
console.log(errs.length ? '  errors: ' + errs.join(' | ') : '  no page errors');
await browser.close();
