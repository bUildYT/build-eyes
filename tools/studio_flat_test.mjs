// bUild sTudio · FLAT (PC mouse / phone touch) + full VR world: mouse draws, sculpts, paints, palette clicks, orbit, then VR mode.
import { chromium } from 'playwright';
import path from 'node:path'; import fs from 'node:fs';
const CH = path.join(process.env.LOCALAPPDATA, 'Google/Chrome/Application/chrome.exe');
const b = await chromium.launch({ executablePath: CH, headless: true, args: ['--ignore-certificate-errors', '--use-angle=d3d11', '--enable-unsafe-swiftshader'] });
const ok = (c, m) => { console.log((c ? '  ✓ ' : '  ✗ ') + m); if (!c) process.exitCode = 1; };
const errs = [];
for (const f of ['_work/studio/scene.json']) if (fs.existsSync(f)) fs.renameSync(f, f + '.bak');
const p = await (await b.newContext({ ignoreHTTPSErrors: true, viewport: { width: 1280, height: 800 } })).newPage();
p.on('pageerror', e => errs.push(e.message)); p.on('console', m => m.type() === 'error' && errs.push(m.text()));
await p.goto('https://localhost:8897/studio.html?flat&who=flat'); await p.waitForFunction(() => window.BE && BE.flat && BE.flat.on, null, { timeout: 60000 }); await p.waitForTimeout(800);
const st = () => p.evaluate(() => BE.devState());
const drag = async (pts, btn = 'left') => { await p.mouse.move(...pts[0]); await p.mouse.down({ button: btn }); for (const q of pts.slice(1)) { await p.mouse.move(...q, { steps: 8 }); } await p.mouse.up({ button: btn }); await p.waitForTimeout(250); };
console.log('mouse · tube');
await p.evaluate(() => BE.setTool('tube'));
await drag([[500, 400], [600, 360], [700, 420], [800, 380]]);
let s = await st(); ok(s.objs.length === 1 && +s.objs[0].split(':')[1] > 8, 'tube ' + s.objs);
console.log('mouse · clay on empty space, then more clay ON the clay');
await p.evaluate(() => BE.setTool('clay'));
await drag([[560, 520], [640, 520], [720, 530]]);
await drag([[600, 515], [680, 515]]);
s = await st(); const c = s.objs.find(o => o.startsWith('sculpt')); ok(c && +c.split(':')[1] > 300, 'sculpt ' + c);
console.log('mouse · paint the clay');
await p.evaluate(() => { BE.setTool('paint'); BE.S.color = '#3a8bff'; });
await drag([[580, 520], [700, 525]]);
const blue = () => p.evaluate(() => { const sc = BE.objs.find(o => o.userData.sculpt).userData.sculpt; let n = 0; for (const ch of sc.chunks.values()) for (let i = 0; i < ch.d.length; i++) if (ch.d[i] > -.95 && ch.col[i * 3 + 2] > 160 && ch.col[i * 3] < 140) n++; return n; });
ok(await blue() > 0, 'sculpt painted blue');
console.log('palette click (HTML) = the same palette as in VR');
const box = await p.evaluate(() => { const r = BE.menu.canvas.getBoundingClientRect(), bt = BE.menu.btns.find(b => b.id === 'tool:ribbon'); return [r.left + (bt.x + bt.w / 2) / 1024 * r.width, r.top + (bt.y + bt.h / 2) / 880 * r.height]; });
await p.mouse.click(...box); s = await st(); ok(s.tool === 'ribbon', 'clicked ribbon → ' + s.tool);
console.log('right-drag = orbit');
const cam0 = await p.evaluate(() => BE.world.camera.position.toArray());
await drag([[900, 300], [1000, 320]], 'right'); await p.waitForTimeout(300);
const cam1 = await p.evaluate(() => BE.world.camera.position.toArray());
ok(Math.hypot(cam1[0] - cam0[0], cam1[2] - cam0[2]) > .02, 'camera orbited'); 
s = await st(); ok(s.objs.length === 2, 'orbit drew nothing (' + s.objs.length + ' objs)');
console.log('keys: Ctrl+Z');
await p.keyboard.press('Control+z'); await p.waitForTimeout(200); s = await st();
ok(await blue() === 0, 'Ctrl+Z took the paint off');
await p.screenshot({ path: '_work/studio_flat.png' });
console.log('VR · full world');
await p.evaluate(() => { IWER_DEVICE.primaryInputMode = 'controller'; });
await p.click('#fVR'); await p.waitForFunction(() => BE.world.renderer.xr.isPresenting, null, { timeout: 30000 }); await p.waitForTimeout(1500);
ok(await p.evaluate(() => BE.world.scene.getObjectByName('env').visible), 'VR world (dome + floor) is on');
ok(await p.evaluate(() => BE.world.session.mode || 'immersive-vr') !== 'immersive-ar', 'session is immersive-vr');
await p.screenshot({ path: '_work/studio_vr.png' });
console.log('errors:', errs.length ? errs : 'none'); if (errs.length) process.exitCode = 1;
await b.close();
if (fs.existsSync('_work/studio/scene.json.bak')) fs.renameSync('_work/studio/scene.json.bak', '_work/studio/scene.json');
